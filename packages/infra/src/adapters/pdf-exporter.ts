import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { PdfExporter, InvoicePdfData } from "@cashpilot/application";

/** 1234567 millimes → "1,234.567 DNT" (pure integer formatting, no floats). */
export function formatMillimes(millimes: number): string {
  const sign = millimes < 0 ? "-" : "";
  const abs = Math.abs(millimes);
  const dinars = Math.trunc(abs / 1000).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  return `${sign}${dinars}.${String(abs % 1000).padStart(3, "0")} DNT`;
}

/** D14: a real A4 invoice PDF built with pdf-lib from data the use case loaded. */
export class PdfLibInvoiceExporter implements PdfExporter {
  async exportInvoice(data: InvoicePdfData): Promise<Uint8Array> {
    const pdf = await PDFDocument.create();
    const page = pdf.addPage([595.28, 841.89]);
    const font = await pdf.embedFont(StandardFonts.Helvetica);
    const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
    const green = rgb(0.12, 0.42, 0.31);
    const grey = rgb(0.29, 0.38, 0.34);
    let y = 790;
    const text = (value: string, x: number, size = 10, isBold = false, color = rgb(0, 0, 0)) =>
      page.drawText(value, { x, y, size, font: isBold ? bold : font, color });
    const right = (value: string, xRight: number, size = 10, isBold = false) =>
      page.drawText(value, { x: xRight - (isBold ? bold : font).widthOfTextAtSize(value, size), y, size, font: isBold ? bold : font });

    text(data.companyName, 50, 18, true, green);
    right(`INVOICE ${data.invoice.number}`, 545, 14, true);
    y -= 22;
    right(`Status: ${data.invoice.status.replace("_", " ")}`, 545, 10);
    y -= 30;
    text("Bill to", 50, 9, false, grey);
    text("Issue date", 360, 9, false, grey);
    text("Due date", 460, 9, false, grey);
    y -= 14;
    text(data.customer.name, 50, 11, true);
    text(data.invoice.issueDate, 360, 11);
    text(data.invoice.dueDate, 460, 11);
    for (const extra of [data.customer.email, data.customer.address]) {
      if (!extra) continue;
      y -= 14;
      text(extra, 50, 10, false, grey);
    }

    y -= 40;
    page.drawRectangle({ x: 45, y: y - 6, width: 505, height: 22, color: rgb(0.93, 0.96, 0.93) });
    text("Description", 52, 10, true);
    right("Qty", 360, 10, true);
    right("Unit price", 455, 10, true);
    right("Total", 545, 10, true);
    for (const line of data.invoice.lines) {
      y -= 24;
      text(line.description.slice(0, 55), 52, 10);
      right(String(line.quantity), 360);
      right(formatMillimes(line.unitPriceMillimes), 455);
      right(formatMillimes(line.lineTotalMillimes), 545);
    }

    y -= 36;
    const totals: [string, number][] = [
      ["Total", data.invoice.totalMillimes],
      ["Paid", data.invoice.totalMillimes - data.invoice.remainingMillimes],
      ["Remaining", data.invoice.remainingMillimes],
    ];
    for (const [label, amount] of totals) {
      text(label, 380, 11, label === "Remaining");
      right(formatMillimes(amount), 545, 11, label === "Remaining");
      y -= 18;
    }

    if (data.payments.length > 0) {
      y -= 20;
      text("Payments received", 50, 11, true, green);
      for (const payment of data.payments) {
        y -= 16;
        text(`${payment.paymentDate}  ·  ${payment.method.replace("_", " ")}`, 50, 10, false, grey);
        right(formatMillimes(payment.amountMillimes), 545);
      }
    }

    page.drawText("Generated by CashPilot", { x: 50, y: 40, size: 8, font, color: grey });
    return pdf.save();
  }
}
